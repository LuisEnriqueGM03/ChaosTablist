class Variant:
	"""Geometría de una de las dos fuentes. `pad` = filas de aire encima y debajo del icono."""

	def __init__(self, font, suffix, pad):
		self.font, self.suffix, self.pad = font, suffix, pad
		self.inner = 7 + 2 * pad          # filas del fondo interior
		self.ring = self.inner + 2        # alto total
		self.inner_ascent = 7 + pad       # el fondo empieza en y = -pad
		self.ring_ascent = 8 + pad        # el borde empieza en y = -pad - 1
		self.label_top = 1 + pad          # letras en y = 1..5
		self.icon_top = pad               # icono en y = 0..6


VARIANTS = [Variant("badge", "", 1), Variant("badge_compact", "_c", 0)]


def px(img, x, y, rgba):
	img.putpixel((x, y), rgba)


def bold(rows):
	"""Negrita como la de vanilla: la letra más ella misma desplazada 1 px."""
	out = []
	for row in rows:
		r = list(row + ".")
		for x, ch in enumerate(row):
			if ch != ".":
				r[x + 1] = ch if r[x + 1] == "." else r[x + 1]
		out.append("".join(r))
	return out


def width_of(rows):
	"""Igual que el juego: última columna con algún píxel + 1."""
	w = 0
	for row in rows:
		for x, ch in enumerate(row):
			if ch != ".":
				w = max(w, x + 1)
	return w


def shade(y, rows):
	g = SHADE_INNER if y == rows - 1 else 255
	return (g, g, g, 255)


def draw_glyph(img, x0, y0, rows):
	for y, row in enumerate(rows):
		for x, ch in enumerate(row):
			if ch == "#":
				px(img, x0 + x, y0 + y, WHITE)
			elif ch == "+":
				px(img, x0 + x, y0 + y, GRAY)


def draw_ko(img, x0, y0, rows, top, width, height):
	"""Fondo de `height` filas y `width` columnas con el hueco de `rows` (que empieza en la fila `top`)."""
	for y in range(height):
		for x in range(width):
			r = y - top
			hole = 0 <= r < len(rows) and x < len(rows[r]) and rows[r][x] != "."
			if not hole:
				px(img, x0 + x, y0 + y, shade(y, height))


class Sheet:
	"""Rejilla de glifos de un tamaño de celda fijo, como espera el provider bitmap."""

	def __init__(self, name, cell_w, cell_h, count, cols=16):
		self.name, self.cw, self.ch, self.cols = name, cell_w, cell_h, cols
		self.rows = max(1, (count + cols - 1) // cols)
		self.img = Image.new("RGBA", (cols * cell_w, self.rows * cell_h), (0, 0, 0, 0))
		self.chars = [["\u0000"] * cols for _ in range(self.rows)]

	def cell(self, i, char):
		self.chars[i // self.cols][i % self.cols] = char
		return (i % self.cols) * self.cw, (i // self.cols) * self.ch

	def provider(self, ascent):
		self.img.save(TEX / f"{self.name}.png")
		return {"type": "bitmap", "file": f"chaostablist:font/{self.name}.png", "height": self.ch, "ascent": ascent,
				"chars": ["".join(r) for r in self.chars]}


def build(v):
	"""Escribe las texturas y el JSON de una variante; devuelve los metadatos (iguales en las dos)."""
	providers = []

	# Borde: filas de arriba y abajo + lados sin las esquinas.
	ring = Sheet("ring" + v.suffix, 32, v.ring, len(FILL_WIDTHS) + 1, cols=len(FILL_WIDTHS) + 1)
	for i, w in enumerate(FILL_WIDTHS):
		x0, y0 = ring.cell(i, chr(RING_FILL + i))
		for x in range(w):
			px(ring.img, x0 + x, 0, WHITE)
			px(ring.img, x0 + x, v.ring - 1, (SHADE_RING, SHADE_RING, SHADE_RING, 255))
	x0, y0 = ring.cell(len(FILL_WIDTHS), chr(RING_CAP))
	for y in range(1, v.ring - 1):
		px(ring.img, x0, y, WHITE)
	providers.append(ring.provider(v.ring_ascent))

	inner = Sheet("inner" + v.suffix, 32, v.inner, len(FILL_WIDTHS), cols=len(FILL_WIDTHS))
	for i, w in enumerate(FILL_WIDTHS):
		x0, y0 = inner.cell(i, chr(INNER_FILL + i))
		for x in range(w):
			for y in range(v.inner):
				px(inner.img, x0 + x, y, shade(y, v.inner))
	providers.append(inner.provider(v.inner_ascent))

	keys = list(LABEL.keys())
	names = ["label", "label_ko", "label_bold", "label_bold_ko"]
	sheets = {k: Sheet(k + v.suffix, 8, v.inner, len(keys)) for k in names}
	label_meta = {}
	for i, ch in enumerate(keys):
		rows = LABEL[ch]
		brows = bold(rows)
		w, bw = width_of(rows), width_of(brows)
		x0, y0 = sheets["label"].cell(i, ch)
		draw_glyph(sheets["label"].img, x0, y0 + v.label_top, rows)
		x0, y0 = sheets["label_ko"].cell(i, chr(LABEL_KO + i))
		draw_ko(sheets["label_ko"].img, x0, y0, rows, v.label_top, w + 1, v.inner)
		x0, y0 = sheets["label_bold"].cell(i, chr(LABEL_BOLD + i))
		draw_glyph(sheets["label_bold"].img, x0, y0 + v.label_top, brows)
		x0, y0 = sheets["label_bold_ko"].cell(i, chr(LABEL_BOLD_KO + i))
		draw_ko(sheets["label_bold_ko"].img, x0, y0, brows, v.label_top, bw + 1, v.inner)
		label_meta[ch] = {"w": w, "ko": LABEL_KO + i, "bw": bw, "b": LABEL_BOLD + i, "bko": LABEL_BOLD_KO + i}
	for k in names:
		providers.append(sheets[k].provider(v.inner_ascent))

	icon_names = list(ICONS.keys())
	icons = Sheet("icons" + v.suffix, 7, v.inner, len(icon_names))
	icons_ko = Sheet("icons_ko" + v.suffix, 8, v.inner, len(icon_names))
	icon_meta = []
	for i, name in enumerate(icon_names):
		rows = ICONS[name]
		assert len(rows) == 7 and all(len(r) == 7 for r in rows), name
		w = width_of(rows)
		x0, y0 = icons.cell(i, chr(ICON_BASE + i))
		draw_glyph(icons.img, x0, y0 + v.icon_top, rows)
		x0, y0 = icons_ko.cell(i, chr(ICON_KO + i))
		draw_ko(icons_ko.img, x0, y0, rows, v.icon_top, w + 1, v.inner)
		icon_meta.append({"id": name, "char": ICON_BASE + i, "ko": ICON_KO + i, "width": w, "fb": FALLBACK.get(name, "•")})
	providers.append(icons.provider(v.inner_ascent))
	providers.append(icons_ko.provider(v.inner_ascent))

	advances = {" ": LABEL_SPACE}
	for i in range(8):
		advances[chr(NEG_SPACE + i)] = -(1 << i)
		advances[chr(POS_SPACE + i)] = 1 << i
	providers.insert(0, {"type": "space", "advances": advances})

	(ROOT / f"font/{v.font}.json").write_text(json.dumps({"providers": providers}, indent=2, ensure_ascii=True),
			encoding="utf-8")
	return {"labelSpace": LABEL_SPACE, "label": label_meta, "icons": icon_meta}


def main():
	TEX.mkdir(parents=True, exist_ok=True)
	(ROOT / "font").mkdir(parents=True, exist_ok=True)
	for old in TEX.glob("*.png"):
		old.unlink()
	meta = None
	for v in VARIANTS:
		meta = build(v)
	(ROOT / "badge_meta.json").write_text(json.dumps(meta, indent=1, ensure_ascii=False), encoding="utf-8")
	print(f"{len(LABEL)} letras, {len(ICONS)} iconos")


if __name__ == "__main__":
	main()
